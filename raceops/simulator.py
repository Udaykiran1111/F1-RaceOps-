import random
import time
import uuid
from datetime import datetime, timezone

from .strategy import save_decision


def generate_event(db, race_id="RACE-DEMO", driver_id=None):
    """Generate one synthetic telemetry event for the specified race."""
    race = db.races.find_one({"race_id": race_id})
    if not race:
        raise ValueError(f"Race {race_id!r} does not exist. Create or seed the race first.")
    if race.get("status") in ("COMPLETED", "ABORTED"):
        raise ValueError(f"Race {race_id!r} is {race['status']} and cannot receive new events.")

    if driver_id:
        driver = db.drivers.find_one({"driver_id": driver_id})
        if not driver:
            raise ValueError(f"Driver {driver_id!r} does not exist.")
    else:
        driver = db.drivers.aggregate([{"$sample": {"size": 1}}]).next()

    total_laps = int(race.get("total_laps", 52))
    prior = db.telemetry.find_one(
        {"race_id": race_id, "driver_id": driver["driver_id"]},
        sort=[("timestamp", -1)],
    )
    lap = min(total_laps, (prior or {}).get("lap", 1) + (1 if prior and random.random() < 0.18 else 0))
    age = (prior or {}).get("tyre_age", random.randint(0, 8))
    if random.random() < 0.08:
        old_compound = (prior or {}).get("tyre_compound", "MEDIUM")
        age = 0
        compound = random.choice(["SOFT", "MEDIUM", "HARD"])
        db.pit_stops.insert_one({
            "race_id": race_id,
            "driver_id": driver["driver_id"],
            "lap": lap,
            "duration_seconds": round(random.uniform(2.1, 4.5), 2),
            "old_compound": old_compound,
            "new_compound": compound,
            "position_before": (prior or {}).get("position", 10),
            "position_after": (prior or {}).get("position", 10) + random.choice([-1, 0, 1]),
            "data_origin": "SIMULATED",
            "timestamp": datetime.now(timezone.utc),
        })
    else:
        compound = (prior or {}).get("tyre_compound", random.choice(["SOFT", "MEDIUM", "HARD"]))
        age += 1

    event = {
        "event_id": str(uuid.uuid4()),
        "race_id": race_id,
        "driver_id": driver["driver_id"],
        "timestamp": datetime.now(timezone.utc),
        "lap": lap,
        "sector": random.randint(1, 3),
        "speed_kmh": round(max(80, min(350, random.gauss(275, 27))), 2),
        "throttle_pct": round(random.uniform(15, 100), 1),
        "brake_pct": round(random.uniform(0, 90), 1),
        "tyre_temp_c": round(random.uniform(82, 113), 1),
        "tyre_compound": compound,
        "tyre_age": age,
        "fuel_estimate_kg": round(max(0, 100 - lap * 1.7), 2),
        "lap_time_seconds": round(random.uniform(86, 98) + age * 0.045, 3),
        "position": (prior or {}).get("position", random.randint(1, 20)),
        "weather": race.get("weather", "DRY"),
        "track_temp_c": float(race.get("track_temp_c", 34.0)),
        "data_origin": "SIMULATED",
    }
    db.telemetry.insert_one(event)

    incident = None
    if random.random() < 0.015:
        incident = random.choice(["SAFETY_CAR", "VIRTUAL_SAFETY_CAR"])
        db.incidents.insert_one({
            "race_id": race_id,
            "lap": lap,
            "type": incident,
            "severity": "HIGH",
            "description": "Generated by race simulator",
            "timestamp": datetime.now(timezone.utc),
            "data_origin": "SIMULATED",
        })
    save_decision(db, race_id, driver["driver_id"], event, incident)
    return event


def run_stream(db, interval=1.0, stop_after=None, race_id="RACE-DEMO", driver_id=None):
    """Print a stream of synthetic events for a selected race."""
    count = 0
    while stop_after is None or count < stop_after:
        event = generate_event(db, race_id=race_id, driver_id=driver_id)
        print(
            f'{event["timestamp"].isoformat()} | {event["race_id"]} | '
            f'{event["driver_id"]} | lap {event["lap"]} | '
            f'{event["speed_kmh"]} km/h | tyre {event["tyre_compound"]}/{event["tyre_age"]}'
        )
        count += 1
        time.sleep(interval)
